# 🖼️ FIGURA 3 — HISTOGRAMAS COM KDE: Distribuição da Pontuação por Aula
# =============================================================================
#
# 📖 O que esta figura mostra?
#   A distribuição completa das pontuações dentro de cada aula,
#   combinando histograma + curva KDE + marcadores de média e mediana
#   + resultado do teste de normalidade Shapiro-Wilk.
#
# 📖 O que é um histograma?
#   Divide os dados em intervalos (bins) e conta quantos valores
#   caem em cada intervalo. O eixo Y mostra a densidade de probabilidade
#   (não a contagem bruta) quando density=True — isso permite comparar
#   distribuições com diferentes tamanhos de amostra.
#
# 📖 O que é KDE (Kernel Density Estimation)?
#   É uma curva suave que estima a forma da distribuição dos dados,
#   como uma versão "suavizada" do histograma. Cada ponto de dado
#   contribui com uma função gaussiana (sino), e a KDE é a soma de
#   todas elas. bw_method=0.5 controla a "suavidade" da curva.
#
# 📖 O que é a média vs a mediana no gráfico?
#   Linha vermelha tracejada = média (μ): sensível a outliers
#   Linha laranja pontilhada = mediana (Md): mais robusta
#   Se estiverem próximas → distribuição aproximadamente simétrica.
#   Se a média for mais alta que a mediana → assimetria à direita (outliers altos).
#
# 📖 O que é idx//2 e idx%2?
#   Para organizar 4 gráficos em uma grade 2×2:
#   idx//2 → divisão inteira: 0,1→linha 0 | 2,3→linha 1
#   idx%2  → resto da divisão: 0,2→coluna 0 | 1,3→coluna 1
#   Essa matemática simples distribui automaticamente os subgráficos.
# =============================================================================

