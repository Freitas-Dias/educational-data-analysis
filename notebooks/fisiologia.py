# 🌡️ G2 — HEATMAP: Pontuação média por Turma × Aula
# ---------------------------------------------------------
#
# 📖 O que é um heatmap?
#   Um heatmap (mapa de calor) é uma tabela colorida onde cada célula
#   recebe uma cor proporcional ao seu valor numérico.
#   Cores quentes (vermelho/laranja) = valores altos.
#   Cores frias (amarelo claro) = valores baixos.
#   No matplotlib/seaborn, o mapa de cores é chamado de 'cmap'.
#
# 📖 O que é uma pivot table?
#   É uma tabela de dupla entrada criada pelo pandas. Aqui:
#     Linhas   → turmas (2021, 2022, ..., 2026)
#     Colunas  → aulas (Aula 1, ..., Aula 4)
#     Valores  → média de pontuação de cada combinação turma+aula
#
#   Essa estrutura é perfeita para o heatmap: cada célula da tabela
#   vira uma célula colorida no gráfico.
#
# 📖 Como ler este gráfico?
#   Procure padrões nas linhas (turmas melhores ou piores em geral)
#   e nas colunas (aulas consistentemente mais fáceis ou difíceis).
#   Uma linha inteira mais escura → aquela turma foi melhor em todas as aulas.
#   Uma coluna inteira mais clara → aquela aula é mais difícil para todos.
# ---------------------------------------------------------

ax2 = fig.add_subplot(gs[0, 1])

