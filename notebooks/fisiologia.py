    #    va='bottom' = o texto fica acima da coordenada y especificada.

# Brackets de significância estatística entre pares de aulas
# 📖 Os brackets são desenhados com ax.plot() usando coordenadas manuais.
#    A lista sig_pairs define quais pares têm diferença significativa
