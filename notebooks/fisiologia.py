# 📦 G1 — BOXPLOT: Pontuação por Aula
# ---------------------------------------------------------
#
# 📖 O que é um boxplot?
#   O boxplot (diagrama de caixas) é um dos gráficos mais usados em
#   estatística porque resume 5 informações em uma só figura:
#
#     │ Bigode superior → valor máximo (excluindo outliers)
#     ┌─────────────────┐
#     │      Q3 (75%)   │ ← 75% dos dados estão ABAIXO desta linha
#     │─────────────────│ ← mediana (50%)
#     │      Q1 (25%)   │ ← 25% dos dados estão ABAIXO desta linha
#     └─────────────────┘
#     │ Bigode inferior → valor mínimo (excluindo outliers)
#     ○ Pontos fora dos bigodes → outliers
#
# 📖 Como ler este gráfico?
#   Caixas mais altas → maior variabilidade nas notas.
#   Mediana alta → a maioria dos estudantes foi bem.
#   Mediana perto do Q1 → distribuição assimétrica (muitos com nota baixa).
#
# 📖 Interpretação esperada:
#   Se as caixas estiverem em alturas muito diferentes entre aulas,
#   isso indica que as aulas têm dificuldades distintas.
#   Os brackets com *** indicam pares de aulas com diferença
#   estatisticamente significativa (p < 0,001 após Bonferroni).
# ---------------------------------------------------------

