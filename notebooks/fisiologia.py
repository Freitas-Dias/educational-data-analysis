# 📉 TABELA B5 — Teste de Tendência Temporal (Spearman com ordenamento)
# -----------------------------------------------------------------------------
#
# 📖 O que este teste avalia?
#   Verifica se existe uma tendência sistemática ao longo do tempo —
#   ou seja, se os valores de cada variável estão aumentando ou
#   diminuindo de forma consistente de 2021 a 2026.
#
# 📖 Como funciona?
#   Convertemos o ano da turma em número (2021, 2022, ..., 2026) e
#   calculamos a correlação de Spearman entre esse número ordenado e
#   cada variável. Um ρ negativo e significativo indica declínio.
#   Esta abordagem é funcionalmente equivalente ao teste de
#   Jonckheere-Terpstra para tendências ordenadas.
#
# 📖 Por que não usar regressão linear aqui?
#   A regressão linear assumiria normalidade dos resíduos.
#   Spearman com ranking é mais robusto para dados ordinais e
#   não-normais, como os desta análise.
#
# 📖 Como interpretar?
#   ρ = -0,28, p < 0,001 na didática significa que, conforme o ano
#   avança de 2021 para 2026, a avaliação da didática tende a ser
#   sistematicamente menor — não por acaso (p < 0,001).
# -----------------------------------------------------------------------------

print("\n\nTabela B5 — Teste de Tendência Temporal (Spearman ρ com ordem do ano):")

# Cria coluna numérica do ano para usar como variável ordinal no teste
