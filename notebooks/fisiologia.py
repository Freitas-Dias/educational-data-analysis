# 📖 Como usar essa tabela?
#   Cada célula mostra o desempenho médio de uma turma em uma aula específica.
#   Comparando linhas: vê-se se uma turma foi melhor que outra em geral.
#   Comparando colunas: vê-se se uma aula foi mais difícil do que outra.
#   Células muito diferentes na mesma coluna → variabilidade entre turmas.
