def verificar_e_carregar_arquivos(diretorio: str, mapeamento_arquivos: dict) -> dict:
    """
    Verifica se os arquivos .xlsx estão presentes no diretório informado,
    valida sua estrutura mínima e retorna os DataFrames carregados.

    Parâmetros
    ----------
    diretorio : str
        Caminho da pasta onde os arquivos devem estar salvos.
        Exemplo: "/home/usuario/dados/" ou "C:/Dados/Fisiologia/"

    mapeamento_arquivos : dict
        Dicionário com os nomes das aulas como chaves e os nomes
        dos arquivos como valores.
        Exemplo: {"Aula 1": "Atividade - Fisiologia Aula 1 (respostas).xlsx"}

    Retorna
    -------
    dict
        Dicionário com o nome de cada aula como chave e seu DataFrame
        carregado como valor. Apenas arquivos válidos são incluídos.

    Levanta
    -------
    SystemExit
        Se nenhum arquivo for encontrado, o script é interrompido com
        mensagem orientativa para o usuário.
    """

    print("=" * 65)
    print("📂 VERIFICAÇÃO DOS ARQUIVOS DE ENTRADA")
    print("=" * 65)
    print()
    print("📋 Arquivos esperados:")
    for aula, nome in mapeamento_arquivos.items():
        print(f"   • {aula}: {nome}")
    print()
    print(f"📁 Diretório de busca: {diretorio}")
    print("-" * 65)

    # Dicionário que armazenará os DataFrames carregados com sucesso
    # 📖 Um DataFrame é uma tabela de dados com linhas e colunas — a
    #    estrutura central do pandas, similar a uma planilha do Excel.
    dataframes_carregados = {}

    # Contadores para feedback ao usuário
    encontrados = 0
    ausentes    = 0

    # Iteramos sobre cada par (nome da aula, nome do arquivo)
    # 📖 O método .items() de um dicionário retorna pares (chave, valor)
    #    que podem ser desempacotados diretamente no for.
    for aula, nome_arquivo in mapeamento_arquivos.items():

        caminho_completo = os.path.join(diretorio, nome_arquivo)
        # 📖 os.path.join() une o diretório e o nome do arquivo de forma
        #    segura, usando o separador correto para cada sistema operacional
        #    (/ no Linux/Mac, \ no Windows).

        if os.path.exists(caminho_completo):
            # Arquivo encontrado — tentamos carregá-lo
            try:
                df_teste = pd.read_excel(caminho_completo, nrows=2)
                # 📖 nrows=2 carrega apenas as 2 primeiras linhas para
                #    verificar se o arquivo é válido sem consumir memória.

                # Verificação mínima: o arquivo precisa ter ao menos 5 colunas
                if df_teste.shape[1] < 5:
                    print(f"   ⚠️  {aula}: arquivo encontrado mas com estrutura"
                          f" inesperada ({df_teste.shape[1]} coluna(s)). "
                          f"Esperadas: 5 colunas.")
                    ausentes += 1
                    continue

                # Arquivo válido — carrega completo
                dataframes_carregados[aula] = pd.read_excel(caminho_completo)
                n_linhas = len(dataframes_carregados[aula])
                print(f"   ✅ {aula}: carregado com sucesso — {n_linhas} registros")
                encontrados += 1

            except Exception as erro:
                # Captura qualquer erro de leitura (arquivo corrompido, formato errado etc.)
                print(f"   ❌ {aula}: erro ao ler o arquivo → {erro}")
                ausentes += 1

        else:
            # Arquivo não encontrado no diretório
            print(f"   ❌ {aula}: arquivo NÃO encontrado → {nome_arquivo}")
            ausentes += 1

    # Exibe resumo da verificação
    print()
    print("-" * 65)
    print(f"📊 Resultado: {encontrados} arquivo(s) carregado(s), "
          f"{ausentes} ausente(s).")
    print("=" * 65)
    print()

    # Se nenhum arquivo foi carregado, interrompe o script
    if encontrados == 0:
        print("🚫 ERRO CRÍTICO: Nenhum arquivo válido foi encontrado.")
        print()
        print("📌 Como resolver:")
        print("   1. Salve os arquivos .xlsx na pasta indicada acima.")
        print("   2. Certifique-se de que os nomes estão exatamente iguais")
        print("      aos listados em 'Arquivos esperados'.")
        print("   3. Verifique se os arquivos não estão abertos no Excel.")
        print("   4. Execute o script novamente.")
        raise SystemExit("Execução interrompida: arquivos de entrada ausentes.")

    return dataframes_carregados


