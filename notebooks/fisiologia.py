# 🔗 TABELA A4 — Correlações de Spearman (dados globais)
# -----------------------------------------------------------------------------
#
# 📖 O que é correlação?
#   Mede a força e a direção da relação entre duas variáveis numéricas.
#   O coeficiente ρ (rho) varia de -1 a +1:
#   • ρ = +1 → relação positiva perfeita (uma sobe, a outra também)
#   • ρ =  0 → sem relação linear
#   • ρ = -1 → relação negativa perfeita (uma sobe, a outra desce)
#
# 📖 Por que Spearman e não Pearson?
#   A correlação de Pearson assume normalidade e mede relações lineares.
#   Spearman trabalha com os postos (ranks) dos dados — adequado para
#   dados ordinais (como escalas Likert) ou não-normais.
#
# 📖 Como interpretar o tamanho da correlação?
#   |ρ| < 0,20  → muito fraca
#   |ρ| 0,20–0,39 → fraca
#   |ρ| 0,40–0,59 → moderada
#   |ρ| 0,60–0,79 → forte
#   |ρ| ≥ 0,80  → muito forte
#
# 📖 Atenção: correlação não é causalidade!
#   Mesmo uma correlação forte não prova que uma variável CAUSA a outra.
#   Pode haver uma terceira variável (variável de confusão) explicando
#   a associação observada.
# -----------------------------------------------------------------------------

print("\n\nTabela A4 — Correlações de Spearman (n total válido por par):")

# Define os pares de variáveis a correlacionar
pairs_corr = [
    ('entendimento', 'pontuacao'),    # Autopercepção prediz desempenho?
    ('didatica',     'pontuacao'),    # Avaliação da aula prediz desempenho?
    ('dificuldade',  'pontuacao'),    # Dificuldade percebida afeta desempenho?
    ('entendimento', 'didatica'),     # Efeito de halo: gostou da aula → sentiu que entendeu?
    ('dificuldade',  'entendimento')  # Mais difícil → menos entendimento percebido?
]

for v1, v2 in pairs_corr:
    # .dropna() garante que apenas linhas com ambas as variáveis válidas entrem
    sub = ALL[[v1, v2]].dropna()
    r, p = spearmanr(sub[v1], sub[v2])
    sig = ('***' if p < .001 else '**' if p < .01 else '*' if p < .05 else 'n.s.')

    # :15s formata o texto com 15 caracteres de largura (alinha colunas no print)
    print(f"  {LABELS[v1]:15s} × {LABELS[v2]:15s}: "
          f"ρ={r:+.3f}  p={p:.4f}  {sig}  n={len(sub)}")


