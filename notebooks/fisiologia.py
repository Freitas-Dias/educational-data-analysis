# ── Subetapa 3a: Função de conversão de data ──────────────────────────────────
#
# 📖 Por que o Excel armazena datas como números?
#   O Excel conta os dias a partir de 1º de janeiro de 1900. Então, a data
#   "01/03/2024" é armazenada internamente como o número 45352.
#   Para recuperar o ano, somamos esse número à data de origem do Excel.
#
# 📖 O que é isinstance()?
#   Verifica se uma variável é de um determinado tipo. Aqui verificamos se
#   o valor é numérico (int ou float) antes de tentar convertê-lo.
#
# 📖 O que é hasattr()?
#   Verifica se um objeto possui um determinado atributo. Objetos datetime
#   já possuem o atributo .year, então não precisam de conversão.
#
# 📖 O que é try/except?
#   Um mecanismo de tratamento de erros: o código dentro do 'try' é
#   executado normalmente; se ocorrer algum erro, o 'except' captura e
#   evita que o script trave — retornando None neste caso.

def ts_to_year(v):
    """
    Converte um valor de timestamp (número serial do Excel ou objeto
    datetime) para o ano inteiro correspondente.

    Parâmetro
    ---------
    v : int, float ou datetime
        Valor de data proveniente da coluna 'timestamp' do Excel.

    Retorna
    -------
    int ou None
        Ano da data (ex: 2024), ou None se a conversão falhar.

    Exemplo
    -------
    >>> ts_to_year(45352)
    2024
    >>> ts_to_year(datetime(2023, 8, 15))
    2023
    """
    try:
        if isinstance(v, (int, float)):
            # Soma o número serial à data de origem do Excel (30/12/1899)
            return (datetime(1899, 12, 30) + pd.Timedelta(days=float(v))).year
        # Se já for um objeto datetime, extrai o ano diretamente
        return v.year if hasattr(v, 'year') else None
    except:
        return None   # Retorna None para valores inválidos ou inesperados


