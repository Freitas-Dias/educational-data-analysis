# ---------------------------------------------------------
# 🔵 G4 — SCATTER COM REGRESSÃO: Entendimento × Pontuação
# ---------------------------------------------------------
#
# 📖 O que é um gráfico de dispersão (scatter plot)?
#   Cada ponto representa UM estudante, posicionado de acordo com:
#     Eixo X → seu entendimento percebido (0–10)
#     Eixo Y → sua pontuação real na atividade (0–10)
#
#   A regressão linear é a reta que melhor descreve a tendência
#   geral da relação entre as duas variáveis.
#
# 📖 O que é stats.linregress()?
#   Calcula a regressão linear simples Y = m·X + b, retornando:
#     m  → inclinação da reta (coeficiente angular)
#     b  → ponto onde a reta cruza o eixo Y (intercepto)
#     *_ → outros valores (r², p-valor, erro padrão) — ignorados aqui
#
# 📖 O que é np.linspace()?
#   Gera 50 pontos igualmente espaçados entre o valor mínimo e máximo
#   do entendimento. Usamos esses pontos para traçar a linha de regressão
#   de forma suave — não apenas entre os extremos dos dados reais.
#
# 📖 Como ler este gráfico?
#   Reta com inclinação positiva → quanto mais entendimento percebido,
#   maior a pontuação real (correlação positiva).
#   Reta horizontal (inclinação ≈ 0) → não há relação entre as variáveis.
#   Pontos muito dispersos → correlação fraca mesmo com reta inclinada.
#
# 📖 Interpretação esperada:
#   Correlação de Spearman (ρ ≈ 0,28) indica relação FRACA. Isso significa
#   que os estudantes têm calibração metacognitiva limitada: sentir que
#   entendeu não garante pontuação alta.
# ---------------------------------------------------------

ax4 = fig.add_subplot(gs[1, 0])

for aula, grp in ALL.groupby('aula'):
    sub = grp[['entendimento', 'pontuacao']].dropna()
    # 📖 .dropna() remove linhas com qualquer valor ausente (NaN)
    #    antes de calcular a regressão — evita erros nas funções matemáticas.

    # Plota os pontos do scatter (um ponto = um estudante)
    ax4.scatter(
        sub['entendimento'],
        sub['pontuacao'],
        label=aula,
        alpha=0.30,          # Transparência para visualizar sobreposição de pontos
        s=20,                # Tamanho dos pontos
        color=pal_aula[aula]
    )

    # Calcula a linha de regressão linear
    m, b, *_ = stats.linregress(sub['entendimento'], sub['pontuacao'])

    # Gera pontos X uniformes para traçar a linha
    xv = np.linspace(sub['entendimento'].min(), sub['entendimento'].max(), 50)

    # Plota a linha de regressão
    ax4.plot(xv, m * xv + b, color=pal_aula[aula], lw=2)

ax4.set_title('Entendimento × Pontuação\nLinhas de regressão por aula', fontweight='bold', fontsize=10)
ax4.set_xlabel('Entendimento (0–10)')
ax4.set_ylabel('Pontuação (0–10)')
ax4.legend(fontsize=7.5)


# ---------------------------------------------------------
# 🟩 G5 — HEATMAP: Matriz de Correlações de Spearman
# ---------------------------------------------------------
#
# 📖 O que é uma matriz de correlação?
#   Uma tabela quadrada onde cada célula mostra o coeficiente de
#   correlação entre dois pares de variáveis. A diagonal seria
#   sempre 1,0 (cada variável correlaciona perfeitamente consigo mesma),
#   por isso exibimos apenas o triângulo inferior — evitando redundância.
#
# 📖 Por que Spearman e não Pearson?
#   A correlação de Pearson assume que os dados seguem distribuição
#   normal. Como os dados desta análise NÃO são normais (confirmado
#   pelo Shapiro-Wilk), usamos a correlação de Spearman, que trabalha
#   com os postos (rankings) dos dados em vez dos valores brutos.
#   Ela é robusta para dados ordinais e não-normais.
#
# 📖 O que é np.triu() e mask?
#   np.triu() cria uma matriz de True apenas no triângulo SUPERIOR.
#   Ao usar mask=True nessas posições, o seaborn oculta aquelas células.
#   Assim, o heatmap exibe apenas o triângulo INFERIOR (sem redundância).
#
# 📖 Como ler este gráfico?
#   Escala de cores: verde = correlação positiva forte,
#   vermelho = correlação negativa forte, amarelo = sem correlação.
#   Cada célula mostra o ρ (rho) de Spearman entre as duas variáveis.
#   ρ próximo de +1 → sobem juntas | ρ próximo de -1 → relação inversa.
# ---------------------------------------------------------

ax5 = fig.add_subplot(gs[1, 1])

vars_hm = ['pontuacao', 'entendimento', 'didatica', 'dificuldade']
lbs     = ['Pont.', 'Entend.', 'Didát.', 'Dific.']

# Calcula a matriz de correlação de Spearman
corr_m = ALL[vars_hm].corr(method='spearman')

# Cria máscara para ocultar o triângulo superior (redundante)
mask = np.triu(np.ones_like(corr_m, dtype=bool))
# 📖 np.ones_like(corr_m, dtype=bool) → matriz de True com mesma forma
# 📖 np.triu() → mantém True apenas no triângulo superior (incluindo diagonal)

sns.heatmap(
    corr_m,
    ax=ax5,
    annot=True,
    fmt='.2f',
    cmap='RdYlGn',     # Vermelho (negativo) → Amarelo (zero) → Verde (positivo)
    center=0,          # Centraliza a escala de cores no zero
    mask=mask,         # Oculta triângulo superior
    linewidths=0.5,
    vmin=-1, vmax=1,
    xticklabels=lbs,
    yticklabels=lbs,
    cbar_kws={'shrink': 0.8}
)

ax5.set_title('Matriz de Correlação (Spearman)\nTriângulo inferior', fontweight='bold', fontsize=10)


# ---------------------------------------------------------
# 📊 G6 — GRÁFICO DE BARRAS com IC: Dificuldade por Aula
# ---------------------------------------------------------
#
# 📖 O que este gráfico mostra?
#   A dificuldade média percebida pelos estudantes em cada aula,
#   com barras de erro representando o Intervalo de Confiança de 95%.
#
# 📖 O que é o Intervalo de Confiança (IC 95%)?
#   É uma faixa em torno da média que, com 95% de probabilidade,
#   contém o valor real da população.
#   Calculado como: IC = ±1,96 × SEM
#   onde SEM (Standard Error of the Mean) = DP / √n.
#   Barras de erro menores → estimativa mais precisa da média real.
#
# 📖 O que é a linha tracejada no valor 5?
#   É o ponto médio da escala (0–10), adicionado como referência visual.
#   Barras acima de 5 → dificuldade percebida acima da média da escala.
#
# 📖 Como ler o resultado esperado?
#   O título informa p=0,27, indicando que o Kruskal-Wallis NÃO detectou
#   diferença significativa entre as aulas. Visualmente, as barras devem
#   estar em alturas similares, confirmando que os estudantes percebem
#   todas as aulas como igualmente difíceis.
# ---------------------------------------------------------

ax6 = fig.add_subplot(gs[1, 2])

means = ALL.groupby('aula')['dificuldade'].mean()
sems  = ALL.groupby('aula')['dificuldade'].sem() * 1.96
# 📖 .groupby().mean() → média por aula
# 📖 .groupby().sem()  → erro padrão da média por aula
# 📖 * 1.96 → fator crítico da distribuição normal para IC de 95%

bars = ax6.bar(
    means.index,
    means.values,
    yerr=sems.values,      # Barras de erro (±IC 95%)
    color=COLORS_AULA,
    edgecolor='white',
    capsize=5,             # Tamanho das "tampas" das barras de erro
    alpha=0.85
)

# Linha de referência no ponto médio da escala
ax6.axhline(5, color='gray', linestyle='--', lw=1, alpha=0.7, label='Ponto médio (5)')
# 📖 axhline() traça uma linha horizontal em uma coordenada Y fixa.
#    É útil para adicionar referências como metas, médias ou limites.

ax6.set_ylim(0, 10)
ax6.set_title(
    'Dificuldade Percebida por Aula\n(KW: p=0.27 — sem diferença significativa)',
    fontweight='bold', fontsize=10
)
ax6.set_ylabel('Dificuldade (0–10)')
ax6.legend(fontsize=8)

# Adiciona o valor numérico acima de cada barra
for bar, val in zip(bars, means.values):
    ax6.text(
        bar.get_x() + bar.get_width() / 2,   # Coordenada X = centro da barra
        bar.get_height() + 0.1,               # Coordenada Y = topo + margem
        f'{val:.1f}',
        ha='center', va='bottom',
        fontweight='bold', fontsize=10
    )


