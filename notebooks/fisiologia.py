#
# Criamos 3 funções helper nesta seção:
#   1. desc_table()  → gera tabela de estatística descritiva
#   2. kw_posthoc()  → Kruskal-Wallis + comparações pareadas
#   3. eta2_label()  → classifica o tamanho de efeito η²
# -----------------------------------------------------------------------------

def desc_table(df, group_col):
    """
    Gera uma tabela de estatística descritiva completa para todas as
    variáveis numéricas de interesse, agrupadas por uma coluna categórica.

    Parâmetros
    ----------
    df : pd.DataFrame
        DataFrame contendo os dados a serem descritos.

    group_col : str
        Nome da coluna usada para agrupar os dados.
        Exemplos: 'aula', 'turma'.

    Retorna
    -------
    pd.DataFrame
        Tabela com as estatísticas: n, média, DP, mínimo, Q1, mediana,
        Q3 e máximo — uma linha por combinação de grupo e variável.

    📖 O que é estatística descritiva?
        É o conjunto de medidas que resumem um conjunto de dados:
        • Média     → valor central aritmético
        • DP        → desvio padrão; quão dispersos os dados estão
        • Mediana   → valor do meio quando ordenados (robusta a outliers)
        • Q1 e Q3   → quartis: dividem os dados em 4 partes iguais
        • Min/Max   → valores extremos da distribuição
    """
    rows = []   # Lista que acumulará um dicionário por linha da tabela

    for grp, sub in df.groupby(group_col):
        # 📖 groupby() + iteração retorna pares (nome_do_grupo, sub_DataFrame)

        for v in VARS:
            s = sub[v].dropna()
            # 📖 .dropna() remove os valores NaN antes dos cálculos,
            #    garantindo que as funções estatísticas operem só com dados válidos.

            rows.append({
                'Grupo':   grp,
                'Variável': LABELS[v],     # Usa o rótulo amigável
                'n':       len(s),
                'Média':   round(s.mean(), 2),
                'DP':      round(s.std(), 2),
                'Min':     round(s.min(), 2),
                'Q1':      round(s.quantile(.25), 2),
                'Mediana': round(s.median(), 2),
                'Q3':      round(s.quantile(.75), 2),
                'Max':     round(s.max(), 2)
            })

    # Converte a lista de dicionários em um DataFrame
    # 📖 pd.DataFrame(lista_de_dicts) cria uma tabela onde cada dicionário
    #    vira uma linha e as chaves viram os nomes das colunas.
    return pd.DataFrame(rows)


def kw_posthoc(df, group_col, var, groups):
    """
    Executa o teste de Kruskal-Wallis e, se significativo, realiza
    comparações pareadas com Mann-Whitney corrigidas por Bonferroni.
    Calcula também o tamanho de efeito η² e o r por par.

    Parâmetros
    ----------
    df : pd.DataFrame
        DataFrame com os dados.
    group_col : str
        Coluna de agrupamento (ex: 'aula', 'turma').
    var : str
        Variável dependente a ser testada (ex: 'pontuacao').
    groups : list
        Lista de grupos a comparar (ex: AULAS ou TURMAS).

    Retorna
    -------
    tuple : (H, p_kw, DataFrame de pares, eta²)
        H     → estatística do Kruskal-Wallis
        p_kw  → p-valor global
        pares → DataFrame com resultados dos pares
        eta²  → tamanho de efeito global

    📖 O que é o teste de Kruskal-Wallis?
        É a versão não-paramétrica da ANOVA — usado quando os dados
        NÃO seguem distribuição normal. Testa se pelo menos um grupo
        tem distribuição diferente dos demais.
        H0 (hipótese nula): todos os grupos têm a mesma distribuição.
        Se p < 0,05, rejeitamos H0 — há diferença significativa.

    📖 O que é o teste de Mann-Whitney?
        Compara dois grupos de forma não-paramétrica. Usado aqui
        como post-hoc: após o KW indicar diferença, Mann-Whitney
        identifica QUAIS pares de grupos diferem entre si.

    📖 O que é a correção de Bonferroni?
        Quando fazemos múltiplas comparações, aumentamos a chance
        de encontrar diferenças por acaso (erro Tipo I).
        Bonferroni corrige multiplicando cada p-valor pelo número
        de pares comparados, tornando o critério mais rigoroso.

    📖 O que é tamanho de efeito (η² e r)?
        Mede a magnitude da diferença — não apenas se ela existe.
        η² = 0 a 0,06 → efeito pequeno
        η² = 0,06 a 0,14 → efeito médio
        η² > 0,14 → efeito grande
    """

    # Extrai os dados de cada grupo como arrays numpy, descartando NaN
    g_data = {
        g: df[df[group_col] == g][var].dropna().values
        for g in groups
    }

    # Mantém apenas grupos com ao menos 3 observações (mínimo para testes)
    valid = {g: v for g, v in g_data.items() if len(v) >= 3}

    # Precisa de pelo menos 2 grupos para comparar
    if len(valid) < 2:
        return None, None, None, None

    # Teste de Kruskal-Wallis global
    # 📖 O operador * desempacota o dicionário: passa os arrays como
    #    argumentos separados para kruskal(), que espera grupos individuais.
    H, p_kw = kruskal(*valid.values())

    # Gera todos os pares possíveis entre os grupos válidos
    # 📖 combinations(['A','B','C'], 2) → [('A','B'), ('A','C'), ('B','C')]
    pairs = list(combinations(list(valid.keys()), 2))

    results = []
    for a, b in pairs:
        # Mann-Whitney para cada par
        u, p_raw = mannwhitneyu(valid[a], valid[b], alternative='two-sided')

        # Correção de Bonferroni: multiplica p pelo número de pares
        p_bonf = min(p_raw * len(pairs), 1.0)   # Limita a 1,0 (máximo de probabilidade)

        n1, n2 = len(valid[a]), len(valid[b])

        # Cálculo do r como tamanho de efeito por par
        # 📖 Convertemos o p-valor em z (escore padrão) e normalizamos pelo n total
        z = stats.norm.ppf(1 - p_raw / 2)
        r = z / np.sqrt(n1 + n2)

        # Codifica o nível de significância em asteriscos (convenção científica)
        sig = ('***' if p_bonf < .001 else
               '**'  if p_bonf < .01  else
               '*'   if p_bonf < .05  else 'n.s.')

        results.append({
            'Par':      f"{a} vs {b}",
            'U':        round(u, 1),
            'p_bruto':  round(p_raw, 4),
            'p_bonf':   round(p_bonf, 4),
            'r_ES':     round(r, 3),
            'sig':      sig
        })

    # Cálculo do η² (eta²) para o teste KW global
    # Fórmula: η² = (H - k + 1) / (N - k), onde k = número de grupos
    eta2 = (H - len(valid) + 1) / (len(df[[group_col, var]].dropna()) - len(valid))

    return H, p_kw, pd.DataFrame(results), round(max(eta2, 0), 4)
    # 📖 max(eta2, 0) garante que valores negativos (artefatos numéricos)
    #    sejam apresentados como zero.


def eta2_label(e):
    """
    Classifica o tamanho de efeito η² segundo os critérios de Cohen (1988).

    Parâmetro
    ---------
    e : float
        Valor de η² entre 0 e 1.

    Retorna
    -------
    str : 'GRANDE', 'MÉDIO' ou 'PEQUENO'
    """
    if e >= 0.14: return 'GRANDE'
    if e >= 0.06: return 'MÉDIO'
    return 'PEQUENO'


