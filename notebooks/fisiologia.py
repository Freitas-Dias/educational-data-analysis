def ts_to_year(v):
    """
    Converte número serial do Excel ou objeto datetime para o ano (int).

    📖 Por que isso é necessário?
       O Google Forms salva os timestamps como números no Excel.
       Ex: 44927 → 01/01/2023. Precisamos extrair o ANO para identificar
       a qual turma aquela resposta pertence.
    """
    try:
        if isinstance(v, (int, float)):
            return (datetime(1899, 12, 30) + pd.Timedelta(days=float(v))).year
        return v.year if hasattr(v, 'year') else None
    except:
        return None


