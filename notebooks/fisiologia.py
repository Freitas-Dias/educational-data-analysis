    r, p = spearmanr(sub['turma_num'], sub[v])
    sig = ('***' if p < .001 else '**' if p < .01 else '*' if p < .05 else 'n.s.')
    print(f"  {LABELS[v]:15s}: ρ={r:+.4f}  p={p:.4f}  {sig}  n={len(sub)}")


