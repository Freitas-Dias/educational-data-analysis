# 🖼️ FIGURA 4 — SCATTER COM REGRESSÃO E IC: Entendimento × Pontuação por Aula
# =============================================================================
#
# 📖 O que esta figura mostra?
#   A relação entre o entendimento percebido e a pontuação real,
#   com reta de regressão e faixa de Intervalo de Confiança de 95%
#   para cada uma das 4 aulas separadamente.
#
# 📖 Por que separar por aula em vez de usar o total?
#   Correlações globais podem mascarar padrões específicos de cada aula.
#   Uma aula pode ter relação forte (a autopercepção prediz bem o desempenho)
#   enquanto outra tem relação nula ou negativa. Ver cada aula separadamente
#   revela essa heterogeneidade — efeito chamado de Paradoxo de Simpson.
#
# 📖 O que é o IC da regressão?
#   A faixa sombreada ao redor da reta de regressão representa a
#   incerteza sobre onde a reta "verdadeira" está. É calculada
#   analiticamente usando a distribuição t de Student:
#
#   IC = ŷ ± t(0.975) × SE(ŷ)
#
#   onde SE(ŷ) depende da distância de cada ponto X ao centro dos dados.
#   Pontos nas extremidades do gráfico têm IC mais largo (menos dados →
#   mais incerteza). O centro tem IC mais estreito.
#
# 📖 O que é stats.t.ppf(0.975, df=n-2)?
#   ppf = Percent Point Function (inversa da CDF).
#   stats.t.ppf(0.975, df=n-2) retorna o valor crítico t para 95% de
#   confiança com n-2 graus de liberdade (df).
#   Para amostras grandes, esse valor se aproxima de 1,96 (valor z).
#
# 📖 O que é fill_between()?
#   Preenche a área entre dois conjuntos de valores Y, criando a faixa
#   sombreada do IC. alpha=0.15 torna o preenchimento levemente transparente.
# =============================================================================

print("Gerando Figura 4 — Correlações por aula com IC...")

fig4, axes = plt.subplots(2, 2, figsize=(14, 10))
fig4.suptitle(
    'Entendimento Percebido × Pontuação por Aula (com IC da regressão)',
    fontsize=13, fontweight='bold'
)

for idx, (aula, grp) in enumerate(ALL.groupby('aula')):
    ax = axes[idx // 2][idx % 2]

    sub = grp[['entendimento', 'pontuacao']].dropna()

    # Correlação de Spearman para este par de variáveis nesta aula
    r, p = spearmanr(sub['entendimento'], sub['pontuacao'])
    sig = '***' if p < .001 else '**' if p < .01 else '*' if p < .05 else 'n.s.'

    # Scatter plot (um ponto = um estudante)
    ax.scatter(
        sub['entendimento'], sub['pontuacao'],
        alpha=0.35, s=28,
        color=COLORS_AULA[idx],
        edgecolors='none'        # Sem borda nos pontos — visual mais limpo
    )

    # Regressão linear: Y = m·X + b
    # 📖 stats.linregress retorna 5 valores:
    #    m=inclinação, b=intercepto, r2=R², pv=p-valor, se=erro padrão
    m, b, r2, pv, se = stats.linregress(sub['entendimento'], sub['pontuacao'])

    # Pontos uniformes para plotar a reta suavemente
    xv = np.linspace(sub['entendimento'].min() - 0.2, sub['entendimento'].max() + 0.2, 100)

    # Reta de regressão
    ax.plot(xv, m * xv + b, color='black', lw=2)

    # Cálculo analítico do IC 95% da regressão
    n  = len(sub)
    t  = stats.t.ppf(0.975, df=n - 2)       # Valor crítico t para IC 95%
    sx = np.std(sub['entendimento'].values)  # Desvio padrão de X

    # Erro padrão de Ŷ para cada valor em xv
    # 📖 Fórmula: SE(Ŷ) = σ_residual × √[ 1/n + (x-x̄)²/((n-1)·sx²) ]
    se_y = np.sqrt(
        (1/n + (xv - sub['entendimento'].mean())**2 / ((n - 1) * sx**2))
        * (sub['pontuacao'].std()**2 * (1 - r2**2))
    )

    # Faixa do IC 95%
    ax.fill_between(
        xv,
        m * xv + b - t * se_y,   # Limite inferior
        m * xv + b + t * se_y,   # Limite superior
        alpha=0.15,
        color=COLORS_AULA[idx]
    )

    ax.set_title(f'{aula}  (ρ={r:.2f} {sig}, n={n})', fontweight='bold')
    ax.set_xlabel('Entendimento (0–10)')
    ax.set_ylabel('Pontuação (0–10)')
    ax.set_xlim(0, 11)
    ax.set_ylim(-0.5, 11)

plt.tight_layout()
plt.savefig(OUT + 'fig4_correlacoes.png', dpi=150, bbox_inches='tight')
plt.close()
print("✅ Fig 4 salva: fig4_correlacoes.png")


