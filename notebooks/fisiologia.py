#   Antes do melt: uma linha por estudante, com colunas separadas
#   para 'entendimento' e 'didatica'.
#   Depois do melt: duas linhas por estudante — uma para cada variável.
#   Esse formato "longo" (long format) é o que o seaborn espera quando
#   quer colorir por categoria.
#
# 📖 Como ler este gráfico?
